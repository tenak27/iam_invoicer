// Classeur Excel (.xlsx) sans bibliothèque : feuilles avec titres, en-têtes en gras, formats
// monétaire / pourcentage / nombre, largeurs de colonnes et volet figé. Archive ZIP « stockée »
// (sans compression) avec CRC32, lisible par Excel, LibreOffice et Google Sheets.

export type CellFormat = 'text' | 'money' | 'number' | 'percent' | 'int'
export interface SheetColumn { label: string; format?: CellFormat; width?: number }
export interface Sheet {
  name: string
  /** Lignes de titre au-dessus du tableau (ex. nom de l'analyse, période). */
  title?: string[]
  columns: SheetColumn[]
  rows: (string | number | null)[][]
  /** Dernière ligne en gras (totaux). */
  totalRow?: (string | number | null)[]
}

const STYLE = { text: 0, header: 1, money: 2, number: 3, percent: 4, int: 5, title: 6, totalText: 7, totalMoney: 8, totalNumber: 9, totalPercent: 10, totalInt: 11 }

const esc = (s: string) => s.replace(/[<>&"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;' })[c]!).replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')
const colName = (i: number) => {
  let s = ''
  for (i++; i > 0; i = Math.floor((i - 1) / 26)) s = String.fromCharCode(65 + ((i - 1) % 26)) + s
  return s
}

function cell(ref: string, v: string | number | null, style: number): string {
  if (v === null || v === undefined || v === '') return `<c r="${ref}" s="${style}"/>`
  if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}" s="${style}"><v>${v}</v></c>`
  return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(String(v))}</t></is></c>`
}

function sheetXml(s: Sheet): string {
  const out: string[] = []
  let r = 1
  for (const t of s.title ?? []) out.push(`<row r="${r}">${cell(`A${r++}`, t, STYLE.title)}</row>`)
  if (s.title?.length) r++
  const headerRow = r
  out.push(`<row r="${r}">${s.columns.map((c, i) => cell(`${colName(i)}${r}`, c.label, STYLE.header)).join('')}</row>`)
  r++
  const styleOf = (f: CellFormat | undefined, total = false) =>
    total ? ({ money: STYLE.totalMoney, number: STYLE.totalNumber, percent: STYLE.totalPercent, int: STYLE.totalInt, text: STYLE.totalText } as const)[f ?? 'text'] : ({ money: STYLE.money, number: STYLE.number, percent: STYLE.percent, int: STYLE.int, text: STYLE.text } as const)[f ?? 'text']
  const line = (vals: (string | number | null)[], total: boolean) => {
    out.push(`<row r="${r}">${vals.map((v, i) => {
      const f = s.columns[i]?.format
      // Pourcentages stockés en fraction (12,5 % → 0,125) pour le format Excel
      const val = f === 'percent' && typeof v === 'number' ? v / 100 : v
      return cell(`${colName(i)}${r}`, val, styleOf(f, total))
    }).join('')}</row>`)
    r++
  }
  for (const row of s.rows) line(row, false)
  if (s.totalRow) line(s.totalRow, true)
  const cols = s.columns.map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width ?? (c.format && c.format !== 'text' ? 16 : 28)}" customWidth="1"/>`).join('')
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetViews><sheetView workbookViewId="0"><pane ySplit="${headerRow}" topLeftCell="A${headerRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews><cols>${cols}</cols><sheetData>${out.join('')}</sheetData></worksheet>`
}

